  function t(key, params = {}) {
    let s = (S[lang] && S[lang][key]) ?? S.cs[key] ?? key;
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(v);
    return s;
  }

  function apply(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(e.dataset.i18n); });
    root.querySelectorAll("[data-i18n-ph]").forEach((e) => { e.placeholder = t(e.dataset.i18nPh); });
    root.querySelectorAll("[data-i18n-title]").forEach((e) => { e.title = t(e.dataset.i18nTitle); });
    document.documentElement.lang = lang;
  }

  function set(l) {
    if (!S[l] || l === lang) return false;
    lang = l;
    apply();
    return true;
  }

